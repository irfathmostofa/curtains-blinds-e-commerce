export function socialIconKey(label: string, href = "") {
  const key = normalize(label);
  const url = href.toLowerCase();
  const aliases: Record<string, string> = {
    instagram: "instagram",
    ig: "instagram",
    facebook: "facebook",
    fb: "facebook",
    meta: "facebook",
    tiktok: "tiktok",
    pinterest: "pinterest",
    linkedin: "linkedin",
    youtube: "youtube",
    twitter: "twitter",
    x: "x",
    whatsapp: "whatsapp",
    snapchat: "snapchat",
    threads: "threads",
    google: "google",
  };
  if (aliases[key]) return aliases[key];
  for (const [needle, icon] of Object.entries(aliases)) {
    if (url.includes(needle)) return icon;
  }
  return "";
}

